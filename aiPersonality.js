// ================================================================
// ==================== 搜索与回答引擎 ====================
// ================================================================

const PersonaEngine = {

    // 合并所有题库
    getAllItems: function() {
        return [
            ...PersonaQnA.wugong,
            ...PersonaQnA.creation,
            ...PersonaQnA.chitChat
        ];
    },

    // 搜索匹配
    search: function(question) {
        const q = question.toLowerCase();
        const items = this.getAllItems();

        let bestMatch = null;
        let bestScore = 0;

        for (const item of items) {
            let score = 0;
            for (const kw of item.keywords) {
                if (q.includes(kw)) {
                    score += 1;
                }
            }
            // 如果关键词完全匹配，加分
            for (const kw of item.keywords) {
                if (kw.length > 2 && q.includes(kw)) {
                    score += 2;
                }
            }
            if (score > bestScore) {
                bestScore = score;
                bestMatch = item;
            }
        }

        // 阈值：至少匹配1个关键词
        if (bestScore >= 1) {
            return bestMatch;
        }

        return null;
    },

    // 获取回答
    getResponse: function(question) {
        const match = this.search(question);
        if (match) {
            return match.answer;
        }
        return null;
    }
};

